// Calcular las posiciones para el efecto 3D.
function updateCarousel() {
    const isMobile = window.innerWidth <= 600;

    const spacing = isMobile ? 112 : 145;
    const depth = isMobile ? 65 : 95;
    const rotation = 38;

    cards.forEach((card, index) => {
        let offset = index - currentIndex;

        // Encontrar la distancia más corta entre tarjetas.
        if (offset > songs.length / 2) {
            offset -= songs.length;
        }

        if (offset < -songs.length / 2) {
            offset += songs.length;
        }

        const distance = Math.abs(offset);
        const isActive = offset === 0;
        const isVisible = distance <= 2;

        const x = offset * spacing;
        const z = isActive ? 0 : -distance * depth;
        const yRotation = -offset * rotation;
        const scale = isActive ? 1 : Math.max(0.72, 1 - distance * 0.12);

        card.style.transform = `
            translateX(${x}px)
            translateZ(${z}px)
            rotateY(${yRotation}deg)
            scale(${scale})
        `;

        card.style.zIndex = String(10 - distance);
        card.style.opacity = isVisible ? String(1 - distance * 0.15) : "0";
        card.style.pointerEvents = isVisible ? "auto" : "none";

        card.classList.toggle("active", isActive);
        card.classList.toggle("hidden-card", !isVisible);

        card.setAttribute("aria-current", isActive ? "true" : "false");
        card.tabIndex = isVisible ? 0 : -1;
    });

    const song = songs[currentIndex];

    currentTitle.textContent = song.title;
    currentArtist.textContent = song.artist;
    songCounter.textContent =
        `${String(currentIndex + 1).padStart(2, "0")} / ${songs.length}`;

    dots.forEach((dot, index) => {
        dot.classList.toggle("active", index === currentIndex);
        dot.setAttribute("aria-pressed", String(index === currentIndex));
    });
}

function nextSong() {
    currentIndex = (currentIndex + 1) % songs.length;
    updateCarousel();
}

function previousSong() {
    currentIndex = (currentIndex - 1 + songs.length) % songs.length;
    updateCarousel();
}

document.getElementById("nextBtn").addEventListener("click", nextSong);
document.getElementById("prevBtn").addEventListener("click", previousSong);

// Abrir la ventana de la letra.
function openLyrics() {
    const song = songs[currentIndex];

    lastFocusedElement = document.activeElement;

    lyricsTitle.textContent = song.title;
    lyricsArtist.textContent = song.artist;
    lyricsArt.textContent = song.symbol;
    lyricsArt.style.backgroundColor = `${song.color}55`;

    lyricsContent.replaceChildren();

    if (song.lyrics.trim()) {
        // El contenido se inserta como texto, no como HTML.
        lyricsContent.textContent = song.lyrics;
    } else {
        const placeholder = document.createElement("p");
        placeholder.className = "lyrics-placeholder";
        placeholder.textContent =
            "Aquí aparecerá la letra de esta canción. " +
            "Puedes agregar el texto que hayas escrito o tengas permiso de utilizar.";
        lyricsContent.appendChild(placeholder);
    }

    modal.classList.add("open");
    modal.setAttribute("aria-hidden", "false");
    document.body.classList.add("modal-open");

    document.getElementById("closeModal").focus();
}

function closeLyrics() {
    modal.classList.remove("open");
    modal.setAttribute("aria-hidden", "true");
    document.body.classList.remove("modal-open");

    if (lastFocusedElement && typeof lastFocusedElement.focus === "function") {
        lastFocusedElement.focus();
    }
}

document.getElementById("openLyrics").addEventListener("click", openLyrics);
document.getElementById("closeModal").addEventListener("click", closeLyrics);
document.getElementById("backButton").addEventListener("click", closeLyrics);
document.getElementById("modalBackdrop").addEventListener("click", closeLyrics);

// Controles con el teclado.
document.addEventListener("keydown", (event) => {
    if (modal.classList.contains("open")) {
        if (event.key === "Escape") {
            closeLyrics();
        }
        return;
    }

    if (event.key === "ArrowRight") {
        nextSong();
    } else if (event.key === "ArrowLeft") {
        previousSong();
    } else if (event.key === "Enter" &&
               document.activeElement === cardStage) {
        openLyrics();
    }
});

